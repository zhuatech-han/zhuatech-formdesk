create table form_definition (id bigint auto_increment primary key,
department_id bigint not null,
creator_id bigint not null,
title varchar(160) not null,
description text not null,
category varchar(60) not null,
schema_json longtext not null,
consent_text text not null,
public_key varchar(80) not null,
status varchar(30) not null,
published_id bigint,
closes_at timestamp(6),
version bigint not null,
created_at timestamp(6) not null,
unique(public_key),
foreign key(department_id) references department(id),
foreign key(creator_id) references account(id));
create table form_revision (id bigint auto_increment primary key,
form_id bigint not null,
number int not null,
title varchar(160) not null,
description text not null,
schema_json longtext not null,
consent_text text not null,
created_at timestamp(6) not null,
unique(form_id,number),
foreign key(form_id) references form_definition(id));
create table submission (id bigint auto_increment primary key,
form_id bigint not null,
revision_id bigint not null,
token_hash varchar(64) not null,
answers_json longtext not null,
status varchar(30) not null,
assignee_id bigint,
request_note text not null,
consented boolean not null,
version bigint not null,
created_at timestamp(6) not null,
updated_at timestamp(6) not null,
unique(token_hash),
foreign key(form_id) references form_definition(id),
foreign key(revision_id) references form_revision(id),
foreign key(assignee_id) references account(id));
create table submission_event (id bigint auto_increment primary key,
submission_id bigint not null,
actor varchar(80) not null,
action varchar(60) not null,
note text not null,
created_at timestamp(6) not null,
foreign key(submission_id) references submission(id));
create table attachment (id bigint auto_increment primary key,
submission_id bigint not null,
field_key varchar(40) not null,
filename varchar(160) not null,
media_type varchar(80) not null,
size int not null,
content longblob not null,
created_at timestamp(6) not null,
foreign key(submission_id) references submission(id));
create index ix_submission_form_status on submission(form_id,status);
create index ix_submission_assignee on submission(assignee_id,status);
create index ix_form_department on form_definition(department_id,status);
create index ix_attachment_submission on attachment(submission_id);
